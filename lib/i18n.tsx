const DICTS: Record<Lang, Dict> = { bs, en, de, fr, it, rm };

export function translate(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const raw = DICTS[lang][key] ?? de[key] ?? en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "bs", setLang: () => {} });

function detect(): Lang {
  try {
    const saved = localStorage.getItem("glowup-lang") as Lang | null;
    if (saved && saved in DICTS) return saved;
  } catch {
    /* ignore */
  }
  // Baseldytsch is the default; French and Italian browsers get their language.
  const nav = typeof navigator !== "undefined" ? navigator.language.slice(0, 2) : "";
  return (["fr", "it"] as Lang[]).includes(nav as Lang) ? (nav as Lang) : "bs";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("bs");
  useEffect(() => setLangState(detect()), []);
  useEffect(() => {
    document.documentElement.lang = lang === "bs" ? "gsw" : lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("glowup-lang", l);
    } catch {
      /* ignore */
    }
  };
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}

export function useT() {
  const { lang } = useContext(Ctx);
  return (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

/** Translated text for use inside server components. */
export function T({ k, v }: { k: string; v?: Record<string, string | number> }) {
  return <>{useT()(k, v)}</>;
}

export function LangSwitcher() {
  const { lang, setLang } = useLang();
  return (
    <div role="group" aria-label="Language" className="flex flex-wrap gap-0.5 text-sm">
      {LANGS.map((l) => (
        <button
          key={l.id}
          onClick={() => setLang(l.id)}
          aria-pressed={lang === l.id}
          title={l.name}
          className={`rounded-control px-1.5 py-1 sm:px-2 ${lang === l.id ? "bg-ink font-semibold text-sheet" : "text-graphite hover:text-ink"}`}
        >
          {l.id === "bs" ? (
            <>
              <span className="sm:hidden">BS</span>
              <span className="hidden sm:inline">{l.label}</span>
            </>
          ) : (
            l.label
          )}
        </button>
      ))}
    </div>
  );
}
